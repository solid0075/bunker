export function roundJoke(card, mature) {
  if (!card) return 'По итогам совещания ещё одно совещание. Зато протокол готов.';
  const variants = cardJokes[card.title] ?? jokes[card.tag];
  if (variants) return variants[Number(mature)];
  if (card.title === 'Боится темноты') return mature ? 'Завхоз выкрутил лампочку. Бережёт, сука, на случай отключения света.' : 'Завхоз выкрутил лампочку. Говорит, бережёт на случай отключения света.';
  return mature ? 'Кадровый отдел записал это как особенность. Особенностей у нас дохуя. Рабочих систем — по ведомости.' : 'Кадровый отдел записал это как особенность. Особенностей полная ведомость. Осталось докупить рабочие системы.';
}
